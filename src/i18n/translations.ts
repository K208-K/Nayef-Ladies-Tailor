export function formatPriceSar(priceSar: number | undefined, locale: Locale): string {
  if (!priceSar) {
    return locale === 'ar' ? 'السعر عند الاستشارة' : 'Upon Consultation';
  }
  const formatted = new Intl.NumberFormat(locale === 'ar' ? 'ar-SA' : 'en-US').format(priceSar);
  return locale === 'ar' ? `${formatted} ر.س` : `SAR ${formatted}`;
}
